#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Region {
    Kanto,
    Johto,
    Hoenn,
    Sinnoh,
    Modern,
}

impl Region {
    pub const ALL: [Region; 5] = [Region::Kanto, Region::Johto, Region::Hoenn, Region::Sinnoh, Region::Modern];
    pub fn label(self) -> &'static str {
        match self {
            Region::Kanto => "Kanto",
            Region::Johto => "Johto",
            Region::Hoenn => "Hoenn",
            Region::Sinnoh => "Sinnoh",
            Region::Modern => "Modern",
        }
    }
    pub fn of(dex: u16, modern: bool) -> Region {
        if modern {
            return Region::Modern;
        }
        match dex {
            1..=151 => Region::Kanto,
            152..=251 => Region::Johto,
            252..=386 => Region::Hoenn,
            387..=493 => Region::Sinnoh,
            _ => Region::Modern,
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Entry {
    pub dex: u16,
    pub types: (u8, u8),
    pub modern: bool,
    pub unobtainable: bool,
    pub region: Region,
}

pub fn entries() -> Vec<Entry> {
    MOD_DEX
        .iter()
        .map(|&(dex, t1, t2, m, u)| Entry {
            dex,
            types: (t1, t2),
            modern: m == 1,
            unobtainable: u == 1,
            region: Region::of(dex, m == 1),
        })
        .collect()
}

